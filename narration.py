_DIGITS = "零一二三四五六七八九"
_MEASURE_FOR_LIANG = "次层颗枚下条把组个段秒点判发轮溯"


def int_to_cn(n: int) -> str:
    """
    把非负整数转换成中文读法（支持到亿以下）。
    @param n 非负整数
    @returns 中文数字，如 204 → 二百零四、10 → 十
    """
    if n == 0:
        return "零"
    if n >= 10 ** 8:
        high, low = divmod(n, 10 ** 8)
        rest = int_to_cn(low) if low else ""
        return int_to_cn(high) + "亿" + (("零" if low < 10 ** 7 else "") + rest if rest else "")
    if n >= 10 ** 4:
        high, low = divmod(n, 10 ** 4)
        rest = int_to_cn(low) if low else ""
        return int_to_cn(high) + "万" + (("零" if low < 1000 else "") + rest if rest else "")
    units = [(1000, "千"), (100, "百"), (10, "十")]
    out = ""
    zero_pending = False
    for value, unit in units:
        d, n = divmod(n, value)
        if d:
            if zero_pending:
                out += "零"
                zero_pending = False
            out += _DIGITS[d] + unit
        elif out:
            zero_pending = True
    if n:
        if zero_pending:
            out += "零"
        out += _DIGITS[n]
    # 「一十二」读作「十二」
    if out.startswith("一十"):
        out = out[1:]
    return out


def num_to_cn(token: str) -> str:
    """
    把阿拉伯数字串（可带小数）转换成中文读法，小数部分逐位念。
    @param token 如 "16.52"、"2219"
    @returns 如 "十六点五二"
    """
    token = token.replace(",", "")
    if "." in token:
        whole, frac = token.split(".", 1)
        head = int_to_cn(int(whole or "0"))
        if head == "二":
            head = "两"
        return head + "点" + "".join(_DIGITS[int(c)] for c in frac)
    return int_to_cn(int(token))


def strip_markup(text: str) -> str:
    """
    去掉字幕标记，得到纯文本。
    @param text 含 `[术语]` / `**强调**` 的文本
    @returns 纯文本
    """
    return text.replace("**", "").replace("[", "").replace("]", "")


def to_tts(text: str) -> str:
    """
    把显示文本转换成 TTS 友好的口播文本：去标记、按 PRON_FIX 纠多音字、数字与百分比转中文。
    @param text 显示文本
    @returns 口播文本
    """
    s = strip_markup(text)
    for src, dst in PRON_FIX.items():
        s = s.replace(src, dst)
    s = s.replace("「", "").replace("」", "").replace("·", "")
    s = s.replace("——", "，").replace("—", "，")
    s = s.replace("BOSS", "boss").replace("BD", "B D")
    s = re.sub(r"\s*\+\s*", "加", s)
    s = re.sub(r"(\d+(?:\.\d+)?)\s*%\s*~\s*(\d+(?:\.\d+)?)\s*%",
               lambda m: f"百分之{num_to_cn(m.group(1))}到百分之{num_to_cn(m.group(2))}", s)
    s = re.sub(r"(\d+(?:\.\d+)?)\s*%", lambda m: "百分之" + num_to_cn(m.group(1)), s)
    s = re.sub(r"\b2\s*(?=[" + _MEASURE_FOR_LIANG + "])", "两", s)
    s = re.sub(r"\d+(?:\.\d+)?", lambda m: num_to_cn(m.group(0)), s)
    s = re.sub(r"\s+", "", s)
    return s


def display_text(text: str) -> str:
    """
    字幕显示用文本：保留标记，去掉行尾的逗号 / 句号 / 分号 / 冒号。
    @param text 原始行文本
    @returns 显示文本
    """
    return re.sub(r"[，。；：、]+(\*\*)?$", lambda m: m.group(1) or "", text.strip())


def pause_after(text: str) -> str:
    """
    依行尾标点判定句间停顿类型。
    @param text 原始行文本
    @returns "short" | "long"
    """
    tail = strip_markup(text).strip()[-1:]
    return "long" if tail in "。？！" else "short"


def iter_lines():
    """
    逐行产出（镜号, 行号, 行字典），行字典补齐 tts / display / pause 字段。
    @returns 生成器
    """
    for shot in SHOTS:
        for idx, line in enumerate(shot["lines"]):
            item = dict(line)
            item["tts"] = line["tts"] or to_tts(line["text"])
            item["display"] = display_text(line["text"])
            item["pause"] = pause_after(line["text"])
            yield shot["id"], idx, item


